import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd();
const read=f=>readFile(path.join(root,f),'utf8');
test('Room Chat V1 is the only active visual authority and owns mobile geometry',async()=>{
  const html=await read('room_chat.html');
  const css=await read('css/spike-room-chat-next.css');
  assert.doesNotMatch(html,/id="roomMark"|\$\('#roomMark'\)/);
  assert.match(html,/class="channel current" id="channelPicker"/);
  assert.doesNotMatch(html,/class="channel active"/);
  assert.match(html,/state\.channel&&c\.id===state\.channel\.id\?'current':''/);
  assert.match(css,/\.channel\.current\{/);
  assert.match(css,/body\[data-spike-page="room_chat"\] \.toolbar/);
  assert.match(css,/body\[data-spike-page="room_chat"\] \.drawer/);
  assert.match(css,/body\[data-spike-page="room_chat"\] \.drawerBody/);
  assert.match(css,/body\[data-spike-page="room_chat"\] \.communityBanner/);
  assert.match(css,/max-height:min\(82dvh,760px\)/);
  assert.match(css,/min-height:52px/);
});
